const slideKeyOf = (id: string) => `${id}:slide`;

/** The demo pitches as saved folders, in the order shown. */
export const DEMO_FOLDERS: FolderRecord[] = PITCHES.map((p) => ({
  id: p.id,
  name: p.name,
  slideName: p.file,
  audioName: null,
  slide: {
    id: slideKeyOf(p.id),
    folderId: p.id,
    title: p.file,
    filename: p.file,
    storageKey: slideKeyOf(p.id),
    fileType: "application/pdf",
    createdAt: SAVED_AT,
  },
  audios: [],
  idea: p.idea,
  keyPoints: p.points.map(([, text]) => text),
  pointSlides: p.points.map(([slide]) => slide),
}));

/** Deck files fetched the first time a browser opens a demo pitch. */
export const DEMO_BLOBS: Record<string, { url: string; type: string }> = Object.fromEntries(
  PITCHES.map((p) => [slideKeyOf(p.id), { url: `/defaults/demo/${p.file}`, type: "application/pdf" }]),
);

/** Each demo pitch's speech text, until the user records or edits their own. */
export const DEMO_SPEECHES: Record<string, string> = Object.fromEntries(PITCHES.map((p) => [p.id, p.speech]));
